// Dump the SLEIGH register file (name, offset, size) as a C header so the
// recompiler runtime can name registers: -postScript RegMap.java <out.h>
// @category SharkTale
import java.io.File;
import java.io.PrintWriter;

import ghidra.app.script.GhidraScript;
import ghidra.program.model.lang.Register;

public class RegMap extends GhidraScript {
	@Override
	protected void run() throws Exception {
		long max = 0;
		try (PrintWriter w = new PrintWriter(new File(getScriptArgs()[0]), "UTF-8")) {
			w.println("/* Generated by tools/ghidra_scripts/RegMap.java: x86:LE:32 register file (offset, size). */");
			w.println("#pragma once");
			for (Register r : currentProgram.getLanguage().getRegisters()) {
				if (!r.getAddressSpace().isRegisterSpace()) {
					continue;
				}
				String n = r.getName().replaceAll("[^A-Za-z0-9_]", "_");
				w.printf("#define REG_%s 0x%x /* size %d */%n", n, r.getOffset(), r.getMinimumByteSize());
				max = Math.max(max, r.getOffset() + r.getMinimumByteSize());
			}
			w.printf("#define REG_FILE_SIZE 0x%x%n", (max + 15) & ~15L);
		}
		println("register file size " + max);
	}
}
