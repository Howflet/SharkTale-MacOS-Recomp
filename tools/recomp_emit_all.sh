#!/bin/zsh
# Emit C for every module in tools/recomp_layout.txt (or just the named ones)
# and regenerate src/Recomp/recomp_modules.h (relocation deltas + table list).
#   tools/recomp_emit_all.sh [Module.dll ...]     (GHIDRA_PROJECT=<dir> to use another project)
set -uo pipefail
ROOT=${0:A:h:h}
GH=/opt/homebrew/opt/ghidra/libexec/support/analyzeHeadless
PROJ=${GHIDRA_PROJECT:-$ROOT/ghidra}   # project from tools/setup_ghidra.sh
typeset -a only; only=("$@")
grep -v '^#' $ROOT/tools/recomp_layout.txt | while read file base; do
  [[ -z $file ]] && continue
  (( ${#only} )) && [[ ${only[(Ie)$file]} -eq 0 ]] && continue
  mod=${file:r}
  $GH $PROJ SharkTale -process $file -noanalysis -readOnly -scriptPath $ROOT/tools/ghidra_scripts \
    -postScript EmitC.java $ROOT/build/recomp $base $mod 2>&1 | grep -oE "EmitC $mod: .*" | cut -c1-120
done
python3 -I - $ROOT <<'PY'
import sys, struct, os
root = sys.argv[1]
sys.path.insert(0, os.path.join(root, 'tools'))
from pe_symbols import PE
lines = ['/* Generated by tools/recomp_emit_all.sh from tools/recomp_layout.txt. */', '#pragma once']
mods = []
for l in open(os.path.join(root, 'tools/recomp_layout.txt')):
    if l.startswith('#') or not l.split():
        continue
    f, base = l.split()
    pe = PE(os.path.join(root, 'orig/System', f))
    mod = os.path.splitext(f)[0]
    lines.append(f'#define RELOC_DELTA_{mod} ((u32){int(base,16) - pe.image_base:#x})')
    mods.append((f, mod, base))
lines.append('#define RECOMP_MODULE_LIST(X) \\')
for f, mod, base in mods:
    lines.append(f'  X("{f}", {mod}, {base}) \\')
lines.append('')
open(os.path.join(root, 'src/Recomp/recomp_modules.h'), 'w').write('\n'.join(lines) + '\n')
print('recomp_modules.h:', len(mods), 'modules')
PY
